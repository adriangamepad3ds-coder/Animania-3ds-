local tiempoTranscurrido = 0
local cancionIniciada = false
local eventoActual = 1
local animacionDisparada = false

function onCreatePost()
    tiempoTranscurrido = 0
    eventoActual = 1
    cancionIniciada = false
end

function onSongStart()
    tiempoTranscurrido = 0
    eventoActual = 1
    cancionIniciada = true
end

function onUpdate(elapsed)
    if not cancionIniciada then return end

    tiempoTranscurrido = getSongPosition() / 1000

    while eventoActual <= #eventosBF and tiempoTranscurrido >= eventosBF[eventoActual][1] do
        local nombreAnimacion = eventosBF[eventoActual][2]
        playAnim('boyfriend', nombreAnimacion, true)
        setProperty('boyfriend.specialAnim', true)
        animacionDisparada = true
        eventoActual = eventoActual + 1
    end
end

